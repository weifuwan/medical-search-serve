
CREATE TABLE SYS_CONFIG (
    ID            NUMBER(19,0)         NOT NULL,
    MODULE_ID     VARCHAR2(32 CHAR),
    CONFIG_CODE   VARCHAR2(128 CHAR)   NOT NULL,
    CONFIG_NAME   VARCHAR2(200 CHAR),
    DESCRIPTION   VARCHAR2(4000 BYTE),
    CONFIG_VALUE  VARCHAR2(4000 BYTE),
    CONFIG_TYPE   VARCHAR2(10 CHAR),
    SORT_CODE     NUMBER(10,0),
    DELETED_FLAG  VARCHAR2(1 CHAR)     DEFAULT '0',
    CREATE_BY     VARCHAR2(32 CHAR),
    CREATE_TIME   DATE,
    UPDATE_BY     VARCHAR2(32 CHAR),
    UPDATE_TIME   DATE,
    SYS_ID        VARCHAR2(32 CHAR),
    WEB_SHOW      VARCHAR2(1 CHAR)     DEFAULT 'Y',
    MODULE_NAME   VARCHAR2(100 CHAR),

    CONSTRAINT PK_SYS_CONFIG PRIMARY KEY (ID)
);

COMMENT ON TABLE SYS_CONFIG IS '系统配置表';

COMMENT ON COLUMN SYS_CONFIG.ID IS '配置主键';
COMMENT ON COLUMN SYS_CONFIG.MODULE_ID IS '模块ID';
COMMENT ON COLUMN SYS_CONFIG.CONFIG_CODE IS '配置编码';
COMMENT ON COLUMN SYS_CONFIG.CONFIG_NAME IS '配置名称';
COMMENT ON COLUMN SYS_CONFIG.DESCRIPTION IS '配置描述';
COMMENT ON COLUMN SYS_CONFIG.CONFIG_VALUE IS '配置值';
COMMENT ON COLUMN SYS_CONFIG.CONFIG_TYPE IS '配置类型';
COMMENT ON COLUMN SYS_CONFIG.SORT_CODE IS '排序';
COMMENT ON COLUMN SYS_CONFIG.DELETED_FLAG IS '删除标记';
COMMENT ON COLUMN SYS_CONFIG.CREATE_BY IS '创建人';
COMMENT ON COLUMN SYS_CONFIG.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN SYS_CONFIG.UPDATE_BY IS '更新人';
COMMENT ON COLUMN SYS_CONFIG.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN SYS_CONFIG.SYS_ID IS '系统标识';
COMMENT ON COLUMN SYS_CONFIG.WEB_SHOW IS '是否在页面展示';
COMMENT ON COLUMN SYS_CONFIG.MODULE_NAME IS '模块名称';

CREATE INDEX IDX_SYS_CONFIG_CODE
    ON SYS_CONFIG (SYS_ID, CONFIG_CODE);




CREATE TABLE SYS_PERMISSION (
    GROUP_CODE         VARCHAR2(32 CHAR),
    ORGANIZATION_CODE  VARCHAR2(32 CHAR),
    PERMISSION_ID      NUMBER(19,0)       NOT NULL,
    PERMISSION_NAME    VARCHAR2(200 CHAR),
    SYS_ID             VARCHAR2(32 CHAR),
    DESCRIPTION        VARCHAR2(1000 CHAR),
    PARENT_ID          NUMBER(19,0)       DEFAULT 0,

    CONSTRAINT PK_SYS_PERMISSION
        PRIMARY KEY (PERMISSION_ID)
);

COMMENT ON TABLE SYS_PERMISSION IS '系统权限表';

COMMENT ON COLUMN SYS_PERMISSION.GROUP_CODE IS '集团编码';
COMMENT ON COLUMN SYS_PERMISSION.ORGANIZATION_CODE IS '机构编码';
COMMENT ON COLUMN SYS_PERMISSION.PERMISSION_ID IS '权限ID';
COMMENT ON COLUMN SYS_PERMISSION.PERMISSION_NAME IS '权限名称';
COMMENT ON COLUMN SYS_PERMISSION.SYS_ID IS '系统标识';
COMMENT ON COLUMN SYS_PERMISSION.DESCRIPTION IS '权限描述及路由配置';
COMMENT ON COLUMN SYS_PERMISSION.PARENT_ID IS '父权限ID，0表示根节点';

CREATE INDEX IDX_SYS_PERMISSION_PARENT
    ON SYS_PERMISSION (SYS_ID, PARENT_ID);



