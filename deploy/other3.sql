COMMENT ON COLUMN LOG_LOGIN.USER_ID IS '用户ID';
COMMENT ON COLUMN LOG_LOGIN.IP IS '登录IP地址';
COMMENT ON COLUMN LOG_LOGIN.LOGIN_TIME IS '登录时间';

