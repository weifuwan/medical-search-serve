import { request } from '@umijs/max';

/** 获取当前的用户 GET /api/currentUser */
export async function currentUser(options?: { [key: string]: any }) {
  return request<{
    data: LOGINAPI.CurrentUser;
  }>('/medical-search-admin/sys/user/info', {
    method: 'GET',
    ...(options || {}),
  });
}

/** 退出登录接口 POST /api/login/outLogin */
export async function outLogin(options?: { [key: string]: any }) {
  return request<Record<string, any>>('/medical-search-admin/logout', {
    method: 'POST',
    ...(options || {}),
  });
}

/** 单点登录 token 验证 POST /medical-search-admin/sso */
export async function checkToken(body: URLSearchParams, options?: { [key: string]: any }) {
    return request<API.RequestResult>('/medical-search-admin/sso', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded',
      },
      data: body,
      ...(options || {}),
    });
  }

/** 登录接口 POST /api/login/account */
export async function login(body: LOGINAPI.LoginParams, options?: { [key: string]: any }) {
  return request<API.RequestResult>('/medical-search-admin/login', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    data: body,
    ...(options || {}),
  });
}

